class MatrixOrbitRepository private constructor(
    val context: MatrixContext,
    private val auth: MatrixAuthRepository,
    private val spaces: MatrixSpacesRepository,
    private val channels: MatrixChannelsRepository,
    private val messages: MatrixMessagesRepository,
    private val users: MatrixUsersRepository,
    private val calls: MatrixCallsRepository,
    private val sync: MatrixSyncRepository
) : OrbitRepository,
    OrbitAuthRepository by auth,
    OrbitSpacesRepository by spaces,
    OrbitChannelsRepository by channels,
    OrbitMessagesRepository by messages,
    OrbitUsersRepository by users,
    OrbitCallsRepository by calls,
    OrbitSyncRepository by sync {

    fun setAccessToken(token: String) { context.accessToken = token }
    fun setUserId(id: String) { context.userId = id }

    companion object {
        operator fun invoke(homeserverUrl: String = "https://matrix.org"): MatrixOrbitRepository {
            val context = MatrixContext(homeserverUrl)
            val auth = MatrixAuthRepository(context)
            val spaces = MatrixSpacesRepository(context)
            val channels = MatrixChannelsRepository(context)
            val messages = MatrixMessagesRepository(context)
            val users = MatrixUsersRepository(context)
            val calls = MatrixCallsRepository(context)
            val sync = MatrixSyncRepository(context, messages, spaces)
            return MatrixOrbitRepository(context, auth, spaces, channels, messages, users, calls, sync)
        }
    }
}

